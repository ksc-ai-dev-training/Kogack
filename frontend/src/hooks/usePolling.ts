import useSWR, { type SWRConfiguration } from 'swr'

// ポーリング共通hook（詳細設計書 総論2.1節・画面設計11.1節・11.4節が定める「3秒間隔」という
// 全体方針の実装。useSWRのrefreshIntervalの薄いラッパーで、チャンネル/DM一覧・スレッド返信等の
// リアルタイム表示に使う）。
//
// 既定値を3000ms→5000msに緩和した（2026-09-10、ユーザー経由で共有された「100人規模で使うと
// ポーリングの負荷がそこそこかかりそうで気になる」という指摘を受けての対応）。会話画面を開いて
// いる利用者1人あたりの常時ポーリング量を試算したところ、サイドバー常時4本＋会話画面で数本が
// いずれも3秒間隔（一部は1秒間隔）で動いており、100人が同時にアクティブな場合バックエンドへ
// 秒間250〜300リクエスト程度が継続的に流れる計算になった。低リスクな軽微修正として、この
// 既定値と後述のメッセージ一覧の間隔を延ばすことにした（体感速度への影響を抑えるため、全てを
// 元の3秒に戻すのではなく5秒に留める）。この既定値を使う一覧（チャンネル・DM・チャンネル
// 参加者・送信予約・スレッド返信・S-08ドキュメント一覧等）は、いずれも他の利用者の操作を
// 数秒以内に検知できれば十分な「一覧の鮮度」用途であり、5秒への緩和で実害は無いと判断した。
// **useMe.ts（セッション切り替えの検知、2026-09-03の実機検証で3秒間隔が必要と確認済み）と
// useMessages.ts（メッセージ一覧、2026-09-04にユーザーの要望で1秒に短縮）はここを使わず
// 個別にrefreshIntervalを指定しており、この既定値変更の影響を受けない**（意図的に対象外）。
export function usePolling<T>(key: string | null, fetcher: (key: string) => Promise<T>, config?: SWRConfiguration) {
  return useSWR<T>(key, fetcher, { refreshInterval: 5000, revalidateOnFocus: true, ...config })
}
